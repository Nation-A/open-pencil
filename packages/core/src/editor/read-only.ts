let warned = false

function guardAction(editor: object, name: string, readOnly: () => boolean): void {
  const original: unknown = Reflect.get(editor, name)
  if (typeof original !== 'function') return
  Reflect.set(editor, name, (...args: unknown[]): unknown => {
    if (readOnly()) {
      if (!warned) {
        warned = true
        console.warn(`[open-pencil] "${name}" ignored: the document is read-only`)
      }
      return undefined
    }
    return Reflect.apply(original, editor, args)
  })
}

/** Wraps the document-changing actions of `editor` so they do nothing while `readOnly()` is true. */
export function guardReadOnly<T extends object>(editor: T, readOnly: () => boolean): T {
  for (const name of DOCUMENT_MUTATING_ACTIONS) guardAction(editor, name, readOnly)
  return editor
}
